class TestCompatibilityRegressions:
    """Regression tests for schema characteristics discovered during real-report validation."""

    def test_floating_point_duration_in_stats(self, tmp_path: pathlib.Path) -> None:
        """Playwright stats duration is a float; ensure it is preserved as float."""
        raw = {
            "suites": [],
            "stats": {
                "duration": 1234.567,
                "expected": 5,
            },
        }
        report_file = tmp_path / "stats_float.json"
        import json
        report_file.write_text(json.dumps(raw), encoding="utf-8")

        parsed = load_report(report_file)
        assert parsed.stats is not None
        assert parsed.stats.duration_ms == 1234.567
        assert parsed.stats.expected == 5

    def test_floating_point_duration_in_result(self, tmp_path: pathlib.Path) -> None:
        """Result duration with fractional milliseconds is supported."""
        raw = {
            "suites": [
                {
                    "title": "suite.spec.js",
                    "specs": [
                        {
                            "title": "spec 1",
                            "tests": [
                                {
                                    "status": "expected",
                                    "results": [
                                        {
                                            "status": "passed",
                                            "duration": 42.85,
                                        }
                                    ],
                                }
                            ],
                        }
                    ],
                }
            ]
        }
        report_file = tmp_path / "result_float.json"
        import json
        report_file.write_text(json.dumps(raw), encoding="utf-8")

        parsed = load_report(report_file)
        res = parsed.suites[0].specs[0].tests[0].results[0]
        assert res.duration_ms == 42.85

    def test_enrich_errors_from_primary_error_object(self, tmp_path: pathlib.Path) -> None:
        """Playwright puts full snippet/stack in result.error while result.errors[0]

        has only location/message. Verify that error details are not lost.
        """
        raw = {
            "suites": [
                {
                    "title": "suite.spec.js",
                    "specs": [
                        {
                            "title": "failing spec",
                            "tests": [
                                {
                                    "status": "unexpected",
                                    "results": [
                                        {
                                            "status": "failed",
                                            "error": {
                                                "message": "primary message",
                                                "stack": "Error: ...\n    at test.js:10:5",
                                                "snippet": "> 10 | failing line",
                                                "location": {"file": "test.js", "line": 10, "column": 5},
                                            },
                                            "errors": [
                                                {
                                                    "message": "primary message",
                                                    "location": {"file": "test.js", "line": 10, "column": 5},
                                                }
                                            ],
                                        }
                                    ],
                                }
                            ],
                        }
                    ],
                }
            ]
        }
        report_file = tmp_path / "enrich_error.json"
        import json
        report_file.write_text(json.dumps(raw), encoding="utf-8")

        parsed = load_report(report_file)
        err = parsed.suites[0].specs[0].tests[0].results[0].errors[0]
        assert err.message == "primary message"
        assert err.stack == "Error: ...\n    at test.js:10:5"
        assert err.snippet == "> 10 | failing line"
        assert err.location is not None
        assert err.location.line == 10
