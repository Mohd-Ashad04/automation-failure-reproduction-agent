"""Validation tests using a real Playwright-generated JSON report.

These tests consume ``tests/fixtures/real_playwright_report.json``, which was
generated by running ``playwright test`` (v1.64.1) against a local HTML fixture
with one passing test and one deliberately failing assertion.
"""

from __future__ import annotations

import pathlib

import pytest

from afra.intake.report_loader import load_report
from afra.models import ParsedReport

FIXTURES_DIR = pathlib.Path(__file__).parent / "fixtures"
REAL_REPORT_PATH = FIXTURES_DIR / "real_playwright_report.json"


@pytest.fixture(scope="module")
def real_report() -> ParsedReport:
    """Load the real Playwright JSON report generated by the browser test suite."""
    assert REAL_REPORT_PATH.exists(), f"Missing fixture: {REAL_REPORT_PATH}"
    return load_report(REAL_REPORT_PATH)


class TestRealReportStructure:
    """Verifies that AFRA safely ingests the actual structure produced by Playwright."""

    def test_report_loaded_successfully(self, real_report: ParsedReport) -> None:
        assert isinstance(real_report, ParsedReport)
        assert real_report.source_file == str(REAL_REPORT_PATH)

    def test_top_level_suites_and_nesting(self, real_report: ParsedReport) -> None:
        # Playwright creates a file-level suite containing describe-block suites
        assert len(real_report.suites) == 1
        file_suite = real_report.suites[0]
        assert file_suite.title == "verify.spec.js"
        assert file_suite.file == "verify.spec.js"
        assert file_suite.source_path == "$.suites[0]"

        # Nested suite corresponding to test.describe('AFRA Local Verification Suite')
        assert len(file_suite.suites) == 1
        describe_suite = file_suite.suites[0]
        assert describe_suite.title == "AFRA Local Verification Suite"
        assert describe_suite.file == "verify.spec.js"
        assert describe_suite.line == 6
        assert describe_suite.column == 6
        assert describe_suite.source_path == "$.suites[0].suites[0]"

    def test_specs_count(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        assert len(describe_suite.specs) == 2


class TestPassingTestEvidence:
    """Verifies evidence extraction for the passing test in the real report."""

    def test_passing_spec_metadata(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        spec = describe_suite.specs[0]

        assert spec.title == "passing test: heading has expected text"
        assert spec.ok is True
        assert spec.line == 7
        assert spec.column == 3
        assert spec.source_path == "$.suites[0].suites[0].specs[0]"

    def test_passing_test_instance_and_result(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        test_inst = describe_suite.specs[0].tests[0]

        assert test_inst.status == "expected"
        assert test_inst.expected_status == "passed"
        assert test_inst.project_name == "chromium"
        assert test_inst.timeout_ms == 10000

        assert len(test_inst.results) == 1
        result = test_inst.results[0]
        assert result.status == "passed"
        assert result.retry == 0
        assert result.worker_index == 0
        assert result.duration_ms is not None
        assert result.duration_ms > 0
        assert result.errors == ()
        assert result.source_path == "$.suites[0].suites[0].specs[0].tests[0].results[0]"


class TestFailingTestEvidence:
    """Verifies evidence extraction for the failing test in the real report."""

    def test_failing_spec_metadata(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        spec = describe_suite.specs[1]

        assert spec.title == "failing test: status has expected text"
        assert spec.ok is False
        assert spec.line == 13
        assert spec.column == 3
        assert spec.source_path == "$.suites[0].suites[0].specs[1]"

    def test_failing_test_instance_status(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        test_inst = describe_suite.specs[1].tests[0]

        assert test_inst.status == "unexpected"
        assert test_inst.expected_status == "passed"
        assert test_inst.project_name == "chromium"

    def test_failing_test_result_error_evidence(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        result = describe_suite.specs[1].tests[0].results[0]

        assert result.status == "failed"
        assert result.retry == 0
        assert result.duration_ms is not None
        assert result.duration_ms > 0
        assert len(result.errors) == 1

        err = result.errors[0]
        # Primary assertion message contains expected and received strings
        assert err.message is not None
        assert "toHaveText" in err.message
        assert "STATUS: NONEXISTENT_FAILING_STATE" in err.message
        assert "STATUS: READY" in err.message

        # Stack trace points to the failing line in the test file
        assert err.stack is not None
        assert "verify.spec.js:17" in err.stack

        # Code snippet contains the failing assertion line
        assert err.snippet is not None
        assert "expect(status)" in err.snippet
        assert "toHaveText" in err.snippet
        assert "NONEXISTENT_FAILING_STATE" in err.snippet

        # Location details
        assert err.location is not None
        assert err.location.file is not None
        assert err.location.file.endswith("verify.spec.js")
        assert err.location.line == 17
        assert err.location.column == 26

    def test_failing_test_attachment_evidence(self, real_report: ParsedReport) -> None:
        describe_suite = real_report.suites[0].suites[0]
        result = describe_suite.specs[1].tests[0].results[0]

        assert len(result.attachments) == 1
        att = result.attachments[0]
        assert att.name == "error-context"
        assert att.content_type == "text/markdown"
        assert att.path is not None
        assert "error-context.md" in att.path


